"""Turn the JSON experiment outputs into a markdown results page."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from .experiment import aggregate


def _fmt(mean: float, std: float) -> str:
    return f"{mean:.3f}" if pd.isna(std) or std == 0 else f"{mean:.3f} ± {std:.3f}"


def benchmark_table(rows: list[dict]) -> str:
    agg = aggregate(rows)
    lines = [
        "| Features | Model | Illicit F1 | Precision | Recall | PR-AUC "
        "| Precision @5% budget | Recall @5% budget |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for _, r in agg.iterrows():
        lines.append(
            f"| {r.feature_set} | {r.model} | {_fmt(r.f1_mean, r.f1_std)} | "
            f"{r.precision_mean:.3f} | {r.recall_mean:.3f} | {_fmt(r.pr_auc_mean, r.pr_auc_std)} | "
            f"{r['precision@5%_mean']:.3f} | {r['recall@5%_mean']:.3f} |"
        )
    return "\n".join(lines)


def write_report(reports: Path) -> Path:
    parts = ["# Results\n", "Generated by `amltriage report` from the JSON files in this folder.\n"]
    bal = reports / "benchmark_balanced.json"
    if bal.exists():
        rows = json.loads(bal.read_text())
        parts += [
            "## Temporal benchmark (train 1-34, test 35-49, class-weighted)\n",
            benchmark_table(rows),
            "",
        ]
    unb = reports / "benchmark_unbalanced.json"
    if unb.exists():
        rows = json.loads(unb.read_text())
        parts += ["## Same models without class re-weighting\n", benchmark_table(rows), ""]
    exp = reports / "explain.json"
    if exp.exists():
        res = json.loads(exp.read_text())
        parts += [
            "## Global SHAP importance (LightGBM, all+graph)\n",
            "| Rank | Feature | mean abs SHAP |",
            "|---|---|---|",
        ]
        for i, (k, v) in enumerate(list(res["global_importance"].items())[:10], 1):
            parts.append(f"| {i} | {k} | {v:.3f} |")
        parts += [
            "",
            "## Per time step: performance vs feature drift\n",
            "| Step | Labelled | Illicit | Illicit F1 | Mean PSI (top-10 features) |",
            "|---|---|---|---|---|",
        ]
        for d in res["drift"]:
            parts.append(
                f"| {d['time_step']} | {d['n_labelled']} | {d['n_illicit']} | "
                f"{d['illicit_f1']:.3f} | {d['mean_psi_top_features']:.3f} |"
            )
        parts.append("")
    out = reports / "results.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out
